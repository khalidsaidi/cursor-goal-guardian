import path from "node:path";

/** Written only while doneCheck.mode is advisory or enforce; removed when off. */
export const DONE_CHECK_RULE_RELATIVE_PATH = path.join(".cursor", "rules", "goal-guardian-done-check.mdc");

export function doneCheckRuleContent(mode: "advisory" | "enforce"): string {
  return [
    "---",
    "description: Goal Guardian done check — how every turn that changed something must end",
    "alwaysApply: true",
    "---",
    "",
    "## The condition",
    "",
    "Any turn in which you ran a command or edited a file ends with ONE of these as the",
    "last section of your final message:",
    "",
    "```",
    "## Done check",
    "1. <evidence for rule 1, or: does not apply: <reason>>",
    "2. …",
    "7. …",
    "sc_1. <evidence that success criterion sc_1 is met, or: does not apply: <reason>>",
    "```",
    "",
    "— seven numbered lines, then one `sc_N.` line per success criterion the contract lists",
    "(`guardian_get_contract`). If it lists none, write no `sc_` lines — do not invent criteria —",
    "and put nothing after the block. Each line either cites concrete evidence — a command in",
    "backticks with what it printed in double quotes (`` `pnpm test` → \"214 passed\" ``), a",
    "`path/to/file.ts:42` reference, or a sample size with both error rates — or reads",
    "`does not apply: <reason>`, or — for anything unfinished — declares the gap as",
    "`gap: <what is unfinished> · closes with: <what would close it> · held by: <who>`.",
    "Never relabel a real gap as \"does not apply\". Bare \"n/a\", \"verified\" or \"see above\"",
    "does not satisfy a line.",
    "",
    "Or, when the task cannot be finished in this session:",
    "",
    "```",
    "## Blocked",
    "- What: <what cannot be done in this session>",
    "- Unblock: <what would unblock it>",
    "- Who: <who holds it>",
    "```",
    "",
    "Goal Guardian checks this block in code against the session tape: a cited command",
    "that never ran, quoted output the command did not print, or a `file:line` past the",
    "end of the file is recorded as **contradicted**. Quote output verbatim; cite only",
    "what you actually ran. The check proves evidence is real, not that it is relevant —",
    "that part is on you: cite what actually supports the rule on that line.",
    mode === "enforce"
      ? "A failing block sends you back with the exact lines to fix."
      : "Results are recorded and shown to the user in the Goal Guardian panel.",
    "",
    "## How to earn it",
    "",
    "Produce what was asked so that it is right in both directions: nothing overstates,",
    "nothing falls short of what the evidence or the requirements support. Both are",
    "failures; only one feels like diligence.",
    "",
    "Scale the method to the stakes: a rename gets one round and one sentence; a number",
    "the user will act on, a design, or a conclusion gets the full treatment. Say which",
    "you applied.",
    "",
    "**Argue to a stop, not to a stopping point.** For each claim, decision, figure or",
    "design: write out the strongest case against it — the version you would struggle to",
    "answer. Answer it. Then write out the case against that answer. Stop after a round",
    "produces no new objection, or after three rounds, and say which. Keep what survives;",
    "record what died, and why. If nothing died, say what was tried and why it held — do",
    "not invent a casualty.",
    "",
    "**A pass that can only move one direction is a bias, not a check.** Every pass must",
    "be able to move the answer up as well as down; say which way it moved and why. Where",
    "a method could err either way, test both ways. Never accept a discard bucket",
    "(\"other\", \"out of scope\", \"edge case\") without sampling it. When a method turns out",
    "to be defective, re-open every conclusion it produced, including the exclusions.",
    "",
    "## The seven rules (one Done-check line each)",
    "",
    "1. Every claim has something behind it: the run, the measurement or the line of code,",
    "   named. A claim you cannot point at gets deleted, and the deletion is said out loud.",
    "2. No internal contradiction. Superseded parts are marked superseded.",
    "3. Measured, not argued. Any rule or heuristic that decides what counts is checked",
    "   against a hand-examined random sample: state the sample size, how it was drawn, and",
    "   the error rate both ways (wrongly included, wrongly excluded).",
    "4. Boundaries are rules, not choices: where the work starts and stops is fixed by a",
    "   stated criterion someone else can apply and get the same answer.",
    "5. Reproducible: same inputs, same result, in one command where possible.",
    "6. Gaps declared, not hidden: what is unfinished, what would close it, who holds it.",
    "7. A number comes with its interval and how it was derived, from one stated method",
    "   applied the same way to every input — not stacked worst cases.",
    "",
    "Lead with what changed and what it means, in short plain English. Then the argument",
    "record. Then the block. What is the user's to decide — product, scope, money,",
    "anything irreversible (deletes, force-pushes, sends, payments, production) — name it,",
    "give your recommendation, and stop there.",
    "",
  ].join("\n");
}
