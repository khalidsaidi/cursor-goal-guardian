"""Guardian's adapter for Google ADK's evaluator, against a fake cursor-agent.

Run: python3 -m unittest discover -s tests (from packages/evaluator), after
  python3 -m pip install --no-deps --only-binary=:all: --target .site -r requirements.txt
The tests that need ADK's dependencies skip without them."""
import json
import os
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
CLI = HERE.parent / "cgg_evaluator" / "cli.py"
ADK = REPO / "third_party" / "adk-python"
SITE = HERE.parent / ".site"
HAVE_DEPS = (SITE / "pydantic").is_dir()

# Answers every judge prompt with FAKE_ANSWER and logs the prompt it was sent.
FAKE_AGENT = r"""#!/usr/bin/env python3
import json, os, sys
a = sys.argv[1:]
p = a[a.index("-p") + 1]
if p.startswith("Read task.md"):
    p = open(os.path.join(a[a.index("--workspace") + 1], "task.md")).read()
open(os.environ["FAKE_LOG"], "a").write(json.dumps({"prompt": p, "mode": a[a.index("--mode") + 1] if "--mode" in a else None,
                                                    "reviewing": os.environ.get("GOAL_GUARDIAN_REVIEWING")}) + "\n")
if os.environ.get("FAKE_FAIL"):
    sys.exit(3)
print(json.dumps({"type": "result", "result": os.environ["FAKE_ANSWER"]}))
"""

def verdicts(**v):
    return "\n\n".join(f"ID: {k}\nProperty: p\nRationale: {k} judged {x}.\nVerdict: {x}" for k, x in v.items())

JOB = {
    "user_query": "Add a min helper to bytes.js\nDone when:\n- bytes.min(list) returns the smallest\n- Tests cover it and pass",
    "items": [{"id": "sc_1", "text": "bytes.min(list) returns the smallest"}, {"id": "sc_2", "text": "Tests cover it and pass"}],
    "conversation": [
        {"role": "assistant", "content": "", "tool_calls": 'edit_file(path="index.js")'},
        {"role": "tool", "content": "--- replaced\n\n+++ with\nfunction min(list) {}", "tool_calls": None},
        {"role": "assistant", "content": "", "tool_calls": 'run_terminal_command(command="npm test")'},
        {"role": "tool", "content": "31 passing", "tool_calls": None},
    ],
    "report": "I report the goal complete.",
}


class EvaluatorTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="gg-evaluator-test-"))
        agent = self.tmp / "agent"
        agent.write_text(FAKE_AGENT)
        agent.chmod(agent.stat().st_mode | stat.S_IEXEC)
        self.log = self.tmp / "agent.log"
        self.env = {**os.environ, "GOAL_GUARDIAN_REVIEWER": str(agent), "FAKE_LOG": str(self.log), "FAKE_ANSWER": verdicts(sc_1="yes", sc_2="yes", extra="yes")}
        self.env.pop("GOAL_GUARDIAN_REVIEWING", None)

    def run_cli(self, job=JOB, site=SITE, **env):
        # -I -S: no site-packages and no user paths, like Guardian's bundled interpreter. Only --site is added.
        r = subprocess.run([sys.executable, "-I", "-S", str(CLI), "--adk", str(ADK / "src"), "--site", str(site)], input=json.dumps(job),
                           capture_output=True, text=True, env={**self.env, **env}, timeout=120)
        self.assertEqual(r.returncode, 0, r.stderr[-800:])
        lines = r.stdout.strip().splitlines()
        self.assertEqual(len(lines), 1, f"stdout must be one JSON line, got: {r.stdout[:400]}")
        return json.loads(lines[0])

    def prompts(self):
        return [json.loads(l) for l in self.log.read_text().splitlines()]

    @unittest.skipUnless(HAVE_DEPS, "ADK's dependencies aren't installed in .site")
    def test_adks_evaluator_judges_each_item_and_the_extra_work_rubric(self):
        out = self.run_cli(FAKE_ANSWER=verdicts(sc_1="yes", sc_2="no", extra="no"))
        self.assertTrue(out["ran"], out)
        self.assertEqual({r["id"]: r["score"] for r in out["rubrics"]}, {"sc_1": 1.0, "sc_2": 0.0, "extra": 0.0})
        self.assertEqual(next(r for r in out["rubrics"] if r["id"] == "sc_2")["rationale"], "sc_2 judged no.")
        self.assertEqual(next(r for r in out["rubrics"] if r["id"] == "sc_2")["property"], "Tests cover it and pass")
        self.assertAlmostEqual(out["overall"], 1 / 3, places=3)
        self.assertEqual(out["calls"], 5)  # ADK's default: five samples per judgement

    @unittest.skipUnless(HAVE_DEPS, "ADK's dependencies aren't installed in .site")
    def test_the_judge_prompt_is_adks_own_and_shows_the_recorded_run(self):
        self.run_cli()
        upstream = (ADK / "src" / "google" / "adk" / "evaluation" / "rubric_based_multi_turn_trajectory_evaluator.py").read_text()
        mission = "Your mission is to evaluate the quality of responses generated by an AI agent in a multi-turn conversation."
        self.assertIn(mission, upstream)
        for p in self.prompts():
            self.assertIn(mission, p["prompt"])
            self.assertIn('"property": "Tests cover it and pass"', p["prompt"])
            self.assertIn("The agent changed nothing that the user's request does not need.", p["prompt"])
            self.assertIn('(tool call): run_terminal_command({"command": "npm test"})', p["prompt"])
            self.assertIn("31 passing", p["prompt"])
            self.assertIn("Do not delegate", p["prompt"])
            self.assertEqual(p["mode"], "ask")
            self.assertEqual(p["reviewing"], "1")

    @unittest.skipUnless(HAVE_DEPS, "ADK's dependencies aren't installed in .site")
    def test_a_goal_with_no_items_is_judged_as_one_rubric(self):
        out = self.run_cli(job={**JOB, "items": []}, FAKE_ANSWER=verdicts(goal="yes", extra="yes"))
        self.assertEqual(sorted(r["id"] for r in out["rubrics"]), ["extra", "goal"])

    @unittest.skipUnless(HAVE_DEPS, "ADK's dependencies aren't installed in .site")
    def test_a_failing_agent_or_an_answer_with_no_verdicts_is_reported_not_raised(self):
        self.assertFalse(self.run_cli(FAKE_FAIL="1")["ran"])
        self.assertFalse(self.run_cli(FAKE_ANSWER="I could not judge this.")["ran"])

    def test_nothing_to_judge_and_missing_pieces_are_reported(self):
        out = self.run_cli(site=self.tmp / "no-such-site")
        self.assertFalse(out["ran"])
        self.assertIn("No module named", out["reason"])  # ADK needs its real dependencies: the standard library alone isn't enough
        r = subprocess.run([sys.executable, "-I", "-S", str(CLI), "--adk", str(self.tmp)], input="{}", capture_output=True, text=True, env=self.env)
        self.assertEqual(json.loads(r.stdout)["reason"], "RuntimeError: ADK's files weren't found")
        if HAVE_DEPS:
            self.assertEqual(self.run_cli(job={**JOB, "conversation": []})["reason"], "nothing to judge: no user request or no recorded actions")

    def test_vendored_adk_files_are_unmodified(self):
        upstream = os.environ.get("ADK_UPSTREAM")
        if not upstream:
            self.skipTest("set ADK_UPSTREAM to a checkout of google/adk-python at the vendored commit")
        for f in ADK.rglob("*"):
            if f.is_file() and f.name != "VENDORED.md" and "__pycache__" not in f.parts:
                self.assertEqual(f.read_bytes(), (Path(upstream) / f.relative_to(ADK)).read_bytes(), str(f))


if __name__ == "__main__":
    unittest.main()
